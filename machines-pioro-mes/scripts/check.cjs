'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
assert.match(html, /<!doctype html>/i, 'Brak doctype HTML');
assert.match(html, /<html[^>]+lang=["']pl["']/i, 'Brak polskiego języka dokumentu');
assert.match(html, /<meta[^>]+name=["']viewport["']/i, 'Brak responsywnego viewport');
const scripts = [...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)].filter(([, attrs]) => !/\bsrc\s*=/.test(attrs) && !/type=["']application\//.test(attrs));
assert.ok(scripts.length > 0, 'Brak kodu aplikacji');
scripts.forEach(([, , code], i) => new vm.Script(code, { filename: 'index.html:inline-' + (i + 1) }));
assert.doesNotMatch(html, /sb_secret_[A-Za-z0-9_-]{12,}/, 'Sekretny klucz w kodzie');
assert.doesNotMatch(html, /(?:TODO|FIXME|reszta kodu)/, 'Niedokończony fragment');
assert.match(html, /isEvalSupported\s*:\s*false/, 'PDF.js wymaga wyłączenia ewaluacji');
const headers = fs.readFileSync(path.join(root, '_headers'), 'utf8');
assert.doesNotMatch(headers, /unsafe-eval/, 'CSP nie może zezwalać na unsafe-eval');
assert.match(headers, /frame-ancestors 'none'/);
console.log('Sprawdzono składnię ' + scripts.length + ' skryptów, format dokumentu i podstawową konfigurację bezpieczeństwa.');
